'use strict';
/**
 * Générateur .xlsx minimal, sans dépendance (archive ZIP « stockée », texte en chaînes intégrées).
 * Les textes ne sont jamais interprétés comme des formules : pas d'injection de formule possible.
 *
 * sheets : [{ name, rows: [[cellule…]…], widths?: [nombre…] }]
 * cellule : texte | nombre | null | { v, s } avec s ∈ 'head' | 'title' | 'money' | 'int' | 'pct' | 'text'
 */
const STYLE = { text: 0, head: 1, money: 2, int: 3, pct: 4, title: 5 };

const CRC_TABLE = (() => { const t = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
function crc32(buf) { let c = 0xFFFFFFFF; for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xFF] ^ (c >>> 8); return (c ^ 0xFFFFFFFF) >>> 0; }

const esc = (s) => String(s).replace(/[&<>"]/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[ch])).replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '');

function colName(i) { let s = ''; for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s; return s; }

function cellXml(cell, r, c) {
  if (cell === null || cell === undefined || cell === '') return '';
  const ref = `${colName(c)}${r + 1}`;
  const obj = typeof cell === 'object' ? cell : { v: cell };
  const style = STYLE[obj.s] ?? (typeof obj.v === 'number' ? STYLE.text : STYLE.text);
  if (typeof obj.v === 'number' && Number.isFinite(obj.v)) return `<c r="${ref}" s="${style}"><v>${obj.v}</v></c>`;
  return `<c r="${ref}" s="${style}" t="inlineStr"><is><t xml:space="preserve">${esc(obj.v)}</t></is></c>`;
}

function sheetXml({ rows, widths }) {
  const cols = widths && widths.length ? `<cols>${widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('')}</cols>` : '';
  const data = rows.map((row, r) => `<row r="${r + 1}">${row.map((cell, c) => cellXml(cell, r, c)).join('')}</row>`).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${cols}<sheetData>${data}</sheetData></worksheet>`;
}

