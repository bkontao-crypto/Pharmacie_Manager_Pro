-- Phase 8 : transferts de stock entre pharmacies d'un MÊME groupe (idempotent)
-- Deux temps : la pharmacie expéditrice expédie (stock sorti en FEFO, lots tracés), la destinataire reçoit (mêmes n° de lot et péremptions).
-- Chaque côté agit dans SA transaction et SON contexte RLS ; le transfert est visible des deux pharmacies (brouillon : expéditrice seule).

CREATE OR REPLACE FUNCTION app_tenant() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT NULLIF(current_setting('app.tenant_id', true), '')::uuid $$;
CREATE OR REPLACE FUNCTION app_bypass() RETURNS boolean LANGUAGE sql STABLE AS
$$ SELECT COALESCE(current_setting('app.bypass_rls', true), '') = 'on' $$;

ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_type_check
  CHECK (type IN ('reception','adjustment','dispensation','sale','return','transfer_out','transfer_in','transfer_return'));

CREATE TABLE IF NOT EXISTS stock_transfers (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number         bigint GENERATED BY DEFAULT AS IDENTITY,
  from_tenant_id uuid NOT NULL REFERENCES tenants(id),
  to_tenant_id   uuid NOT NULL REFERENCES tenants(id),
  status         text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','in_transit','received','cancelled','refused','returned')),
  notes          text,
  refusal_reason text,
  created_by     uuid,
  created_at     timestamptz NOT NULL DEFAULT now(),
  sent_by        uuid,
  sent_at        timestamptz,
  received_by    uuid,
  received_at    timestamptz,
  closed_by      uuid,
  closed_at      timestamptz,
  CHECK (from_tenant_id <> to_tenant_id)
);
CREATE INDEX IF NOT EXISTS stock_transfers_from_idx ON stock_transfers (from_tenant_id, created_at DESC);
CREATE INDEX IF NOT EXISTS stock_transfers_to_idx   ON stock_transfers (to_tenant_id, created_at DESC);

CREATE TABLE IF NOT EXISTS stock_transfer_lines (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  transfer_id           uuid NOT NULL REFERENCES stock_transfers(id) ON DELETE CASCADE,
  from_tenant_id        uuid NOT NULL REFERENCES tenants(id),
  to_tenant_id          uuid NOT NULL REFERENCES tenants(id),
  product_id            uuid NOT NULL REFERENCES products(id),         -- produit de l'expéditrice
  product_name          text NOT NULL,                                  -- copie des attributs (appariement et création côté destinataire)
  dci                   text,
  barcode               text,
  form                  text,
  dosage                text,
  requires_prescription boolean NOT NULL DEFAULT false,
  sale_price            numeric(12,2) NOT NULL DEFAULT 0,
  purchase_price        numeric(12,2) NOT NULL DEFAULT 0,
  quantity              int NOT NULL CHECK (quantity > 0),
  dest_product_id       uuid REFERENCES products(id),                   -- renseigné à la réception
  created_product       boolean NOT NULL DEFAULT false,                 -- produit créé dans le catalogue du destinataire
  UNIQUE (transfer_id, product_id)
);

CREATE TABLE IF NOT EXISTS stock_transfer_lots (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  transfer_id    uuid NOT NULL REFERENCES stock_transfers(id) ON DELETE CASCADE,
  line_id        uuid NOT NULL REFERENCES stock_transfer_lines(id) ON DELETE CASCADE,
  from_tenant_id uuid NOT NULL REFERENCES tenants(id),
  to_tenant_id   uuid NOT NULL REFERENCES tenants(id),
  source_lot_id  uuid NOT NULL REFERENCES stock_lots(id),               -- lot de l'expéditrice (retour du stock en cas d'annulation/refus)
  lot_number     text NOT NULL,
  expiry_date    date NOT NULL,
  quantity       int NOT NULL CHECK (quantity > 0)
);
CREATE INDEX IF NOT EXISTS stock_transfer_lines_tr_idx ON stock_transfer_lines (transfer_id);
CREATE INDEX IF NOT EXISTS stock_transfer_lots_tr_idx  ON stock_transfer_lots (transfer_id);

-- Un transfert ne sort jamais du groupe : vérifié par la base elle-même (en plus de l'application).
CREATE OR REPLACE FUNCTION stock_transfers_check_group() RETURNS trigger LANGUAGE plpgsql AS
$$
BEGIN
  IF (SELECT COALESCE(parent_id, id) FROM tenants WHERE id = NEW.from_tenant_id)
     IS DISTINCT FROM (SELECT COALESCE(parent_id, id) FROM tenants WHERE id = NEW.to_tenant_id) THEN
    RAISE EXCEPTION 'Un transfert ne peut avoir lieu qu''entre pharmacies d''un même groupe';
  END IF;
  RETURN NEW;
END
$$;
DROP TRIGGER IF EXISTS stock_transfers_group_check ON stock_transfers;
CREATE TRIGGER stock_transfers_group_check BEFORE INSERT OR UPDATE OF from_tenant_id, to_tenant_id ON stock_transfers
  FOR EACH ROW EXECUTE FUNCTION stock_transfers_check_group();

-- ---------- RLS : visible des deux pharmacies (le brouillon n'est visible que de l'expéditrice) ----------
ALTER TABLE stock_transfers ENABLE ROW LEVEL SECURITY;      ALTER TABLE stock_transfers FORCE ROW LEVEL SECURITY;
ALTER TABLE stock_transfer_lines ENABLE ROW LEVEL SECURITY; ALTER TABLE stock_transfer_lines FORCE ROW LEVEL SECURITY;
ALTER TABLE stock_transfer_lots ENABLE ROW LEVEL SECURITY;  ALTER TABLE stock_transfer_lots FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS transfers_select ON stock_transfers;
CREATE POLICY transfers_select ON stock_transfers FOR SELECT
  USING (app_bypass() OR from_tenant_id = app_tenant() OR (to_tenant_id = app_tenant() AND status <> 'draft'));
DROP POLICY IF EXISTS transfers_insert ON stock_transfers;
CREATE POLICY transfers_insert ON stock_transfers FOR INSERT
  WITH CHECK (app_bypass() OR (from_tenant_id = app_tenant() AND status = 'draft'));
DROP POLICY IF EXISTS transfers_update ON stock_transfers;
CREATE POLICY transfers_update ON stock_transfers FOR UPDATE
  USING (app_bypass() OR from_tenant_id = app_tenant() OR (to_tenant_id = app_tenant() AND status <> 'draft'))
  WITH CHECK (app_bypass() OR from_tenant_id = app_tenant() OR to_tenant_id = app_tenant());
DROP POLICY IF EXISTS transfers_delete ON stock_transfers;
CREATE POLICY transfers_delete ON stock_transfers FOR DELETE
  USING (app_bypass() OR (from_tenant_id = app_tenant() AND status = 'draft'));

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['stock_transfer_lines','stock_transfer_lots'] LOOP
    EXECUTE format('DROP POLICY IF EXISTS child_select ON %I', t);
    EXECUTE format('CREATE POLICY child_select ON %I FOR SELECT USING (app_bypass() OR EXISTS (SELECT 1 FROM stock_transfers x WHERE x.id = transfer_id))', t);   -- hérite de la visibilité du transfert
    EXECUTE format('DROP POLICY IF EXISTS child_insert ON %I', t);
    EXECUTE format('CREATE POLICY child_insert ON %I FOR INSERT WITH CHECK (app_bypass() OR from_tenant_id = app_tenant())', t);
    EXECUTE format('DROP POLICY IF EXISTS child_update ON %I', t);
    EXECUTE format('CREATE POLICY child_update ON %I FOR UPDATE USING (app_bypass() OR from_tenant_id = app_tenant() OR to_tenant_id = app_tenant()) WITH CHECK (app_bypass() OR from_tenant_id = app_tenant() OR to_tenant_id = app_tenant())', t);
    EXECUTE format('DROP POLICY IF EXISTS child_delete ON %I', t);
    EXECUTE format('CREATE POLICY child_delete ON %I FOR DELETE USING (app_bypass() OR from_tenant_id = app_tenant())', t);
  END LOOP;
END $$;
