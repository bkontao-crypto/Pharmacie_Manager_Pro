-- Phase 2 : Patients, Stocks & Inventaire, Dispensation (idempotent)

CREATE TABLE IF NOT EXISTS patients (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id            uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  last_name            text NOT NULL,
  first_name           text NOT NULL,
  birth_date           date,
  sex                  text CHECK (sex IN ('F','M')),
  phone                text,
  address              text,
  insurance_provider   text,
  insurance_number_enc text,            -- chiffré AES-256-GCM
  allergies            text[] NOT NULL DEFAULT '{}',
  contraindications    text,
  notes_enc            text,            -- chiffré AES-256-GCM
  is_active            boolean NOT NULL DEFAULT true,
  created_by           uuid,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS patients_name_idx ON patients (tenant_id, lower(last_name), lower(first_name));

CREATE TABLE IF NOT EXISTS products (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id            uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name                 text NOT NULL,
  dci                  text,            -- dénomination commune internationale (principe actif)
  barcode              text,
  form                 text,
  dosage               text,
  sale_price           numeric(12,2) NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
  purchase_price       numeric(12,2) NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
  min_stock            int NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  max_stock            int CHECK (max_stock IS NULL OR max_stock >= 0),
  requires_prescription boolean NOT NULL DEFAULT false,
  is_active            boolean NOT NULL DEFAULT true,
  created_at           timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS products_barcode_uq ON products (tenant_id, barcode) WHERE barcode IS NOT NULL;
CREATE INDEX IF NOT EXISTS products_name_idx ON products (tenant_id, lower(name));

CREATE TABLE IF NOT EXISTS stock_lots (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id   uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  product_id  uuid NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  lot_number  text NOT NULL,
  expiry_date date NOT NULL,
  quantity    int NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  received_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, product_id, lot_number)
);
CREATE INDEX IF NOT EXISTS lots_product_idx ON stock_lots (tenant_id, product_id, expiry_date);

CREATE TABLE IF NOT EXISTS stock_movements (
  id         bigserial PRIMARY KEY,
  tenant_id  uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  lot_id     uuid REFERENCES stock_lots(id) ON DELETE SET NULL,
  type       text NOT NULL CHECK (type IN ('reception','adjustment','dispensation')),
  quantity   int NOT NULL,              -- variation signée
  reason     text,
  ref_id     uuid,                      -- ex. ordonnance
  user_id    uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS movements_product_idx ON stock_movements (tenant_id, product_id, id DESC);

CREATE TABLE IF NOT EXISTS prescriptions (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id           uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  number              bigint GENERATED BY DEFAULT AS IDENTITY,
  patient_id          uuid NOT NULL REFERENCES patients(id),
  prescriber_name     text NOT NULL,
  prescribed_on       date NOT NULL,
  status              text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','validated','dispensed','cancelled')),
  notes               text,
  alerts              jsonb NOT NULL DEFAULT '[]'::jsonb,
  alerts_acknowledged boolean NOT NULL DEFAULT false,
  created_by          uuid,
  created_at          timestamptz NOT NULL DEFAULT now(),
  validated_by        uuid,
  validated_at        timestamptz,
  dispensed_by        uuid,
  dispensed_at        timestamptz,
  cancelled_reason    text
);
CREATE INDEX IF NOT EXISTS prescriptions_idx ON prescriptions (tenant_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS prescriptions_patient_idx ON prescriptions (tenant_id, patient_id);

CREATE TABLE IF NOT EXISTS prescription_items (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  prescription_id uuid NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
  product_id      uuid NOT NULL REFERENCES products(id),
  quantity        int NOT NULL CHECK (quantity > 0),
  posology        text
);
CREATE INDEX IF NOT EXISTS items_rx_idx ON prescription_items (prescription_id);

-- ---------- RLS (même principe que la Phase 1) ----------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['patients','products','stock_lots','stock_movements','prescriptions','prescription_items'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format($p$CREATE POLICY tenant_isolation ON %I
      USING      (current_setting('app.bypass_rls', true) = 'on' OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)
      WITH CHECK (current_setting('app.bypass_rls', true) = 'on' OR tenant_id = NULLIF(current_setting('app.tenant_id', true), '')::uuid)$p$, t);
  END LOOP;
END $$;
