-- Nouveaux types de mouvements de stock
ALTER TABLE stock_movements DROP CONSTRAINT IF EXISTS stock_movements_type_check;
ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_type_check
  CHECK (type IN ('reception','adjustment','dispensation','sale','return'));

CREATE TABLE IF NOT EXISTS suppliers (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id    uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  name         text NOT NULL,
  contact_name text,
  phone        text,
  email        text,
  address      text,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS suppliers_name_uq ON suppliers (tenant_id, lower(name));

CREATE TABLE IF NOT EXISTS purchase_orders (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id   uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  number      bigint GENERATED BY DEFAULT AS IDENTITY,
  supplier_id uuid NOT NULL REFERENCES suppliers(id),
  status      text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','sent','partial','received','cancelled')),
  notes       text,
  created_by  uuid,
  created_at  timestamptz NOT NULL DEFAULT now(),
  sent_by     uuid,
  sent_at     timestamptz,
  received_at timestamptz
);
CREATE INDEX IF NOT EXISTS po_idx ON purchase_orders (tenant_id, status, created_at DESC);

CREATE TABLE IF NOT EXISTS purchase_order_items (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id         uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  order_id          uuid NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
  product_id        uuid NOT NULL REFERENCES products(id),
  quantity_ordered  int NOT NULL CHECK (quantity_ordered > 0),
  quantity_received int NOT NULL DEFAULT 0 CHECK (quantity_received >= 0),
  unit_cost         numeric(12,2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
  CHECK (quantity_received <= quantity_ordered)
);
CREATE INDEX IF NOT EXISTS poi_order_idx ON purchase_order_items (order_id);
CREATE INDEX IF NOT EXISTS poi_product_idx ON purchase_order_items (tenant_id, product_id);

CREATE TABLE IF NOT EXISTS sales (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id       uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  number          bigint GENERATED BY DEFAULT AS IDENTITY,
  patient_id      uuid REFERENCES patients(id),
  prescription_id uuid REFERENCES prescriptions(id),
  status          text NOT NULL DEFAULT 'paid' CHECK (status IN ('paid','refunded')),
  subtotal        numeric(12,2) NOT NULL CHECK (subtotal >= 0),
  discount_pct    numeric(5,2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
  discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  total           numeric(12,2) NOT NULL CHECK (total >= 0),
  created_by      uuid,
  created_at      timestamptz NOT NULL DEFAULT now(),
  refunded_by     uuid,
  refunded_at     timestamptz,
  refund_reason   text
);
CREATE INDEX IF NOT EXISTS sales_idx ON sales (tenant_id, created_at DESC);
-- une ordonnance ne peut être facturée qu'une seule fois (hors vente remboursée)
CREATE UNIQUE INDEX IF NOT EXISTS sales_rx_uq ON sales (prescription_id) WHERE prescription_id IS NOT NULL AND status = 'paid';

CREATE TABLE IF NOT EXISTS sale_items (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id  uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  sale_id    uuid NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_id uuid NOT NULL REFERENCES products(id),
  quantity   int NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  unit_cost  numeric(12,2) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0)   -- coût d'achat au moment de la vente (marge)
);
CREATE INDEX IF NOT EXISTS sale_items_sale_idx ON sale_items (sale_id);
CREATE INDEX IF NOT EXISTS sale_items_product_idx ON sale_items (tenant_id, product_id);

CREATE TABLE IF NOT EXISTS sale_item_lots (   -- traçabilité : de quels lots provient chaque vente
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id    uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  sale_item_id uuid NOT NULL REFERENCES sale_items(id) ON DELETE CASCADE,
  lot_id       uuid NOT NULL REFERENCES stock_lots(id),
  quantity     int NOT NULL CHECK (quantity > 0)
);

CREATE TABLE IF NOT EXISTS payments (
  id        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id uuid NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  sale_id   uuid NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  method    text NOT NULL CHECK (method IN ('especes','mobile_money','carte','tiers_payant')),
  amount    numeric(12,2) NOT NULL CHECK (amount > 0),
  reference text
);
CREATE INDEX IF NOT EXISTS payments_sale_idx ON payments (sale_id);

